#!/bin/sh
# Copies setup.sql and the later migrations into the app: automatic setup runs
# them through the Management API, and Settings › Account & Sync › Enter URL and
# key instead offers "Copy setup.sql". Run after editing either file;
# SupabaseSetupFilesTests fails until you do.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
out="$here/../../Packages/BlueboxKit/Sources/Sync/SupabaseSetupFiles.swift"
{
  echo '// Generated by Backend/supabase/embed-in-app.sh from Backend/supabase. Do not edit.'
  echo ''
  echo '/// The SQL a new Supabase project needs, for automatic setup and "Copy setup.sql".'
  echo 'public enum SupabaseSetupFiles {'
  echo '    /// Backend/supabase/setup.sql'
  printf '    public static let setupSQL = #"""\n'
  cat "$here/setup.sql"
  printf '"""#\n\n'
  echo '    /// Backend/supabase/migrations/20261028000000_profiles.sql, for projects set up before profiles.'
  printf '    public static let profilesMigrationSQL = #"""\n'
  cat "$here/migrations/20261028000000_profiles.sql"
  printf '"""#\n\n'
  echo '    /// Backend/supabase/migrations/20261029000000_account_settings.sql, for projects set up before account settings.'
  printf '    public static let accountSettingsMigrationSQL = #"""\n'
  cat "$here/migrations/20261029000000_account_settings.sql"
  printf '"""#\n\n'
  echo '    /// Backend/supabase/migrations/20261029100000_lists.sql, for projects set up before lists.'
  printf '    public static let listsMigrationSQL = #"""\n'
  cat "$here/migrations/20261029100000_lists.sql"
  printf '"""#\n'
  echo '}'
} > "$out"
echo "Wrote $out"
